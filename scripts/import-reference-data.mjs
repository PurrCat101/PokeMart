#!/usr/bin/env node
// One-time reference-data import. NOT run at startup or in tests.
//
// Usage:
//   node import-reference-data.mjs <path-to-PokeAPI/api-data> [--max=1351] [--items] [--sprites]
//
// Reads a LOCAL, PINNED checkout of https://github.com/PokeAPI/api-data and writes:
//   database/seed/010_reference_pokemon.sql   (always)
//   database/seed/011_reference_items.sql     (--items)
//   database/seed/012_seed_catalog.sql        (--items)
//   data/sprites/<id>.png                     (--sprites, downloads images)
//   data/reference-manifest.json              (source commit, counts, checksums)
//
// Assumed layout (verify against the pinned commit before running):
//   data/api/v2/pokemon/<id>/index.json
//   data/api/v2/item/<id>/index.json

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import path from "node:path";

const args = process.argv.slice(2);
const root = args.find((a) => !a.startsWith("--"));
if (!root) {
  console.error("usage: import-reference-data.mjs <api-data-dir> [--max=N] [--items] [--sprites]");
  process.exit(1);
}
const maxArg = args.find((a) => a.startsWith("--max="));
const max = maxArg ? Number(maxArg.split("=")[1]) : 1351;
const wantItems = args.includes("--items");
const wantSprites = args.includes("--sprites");

const SEED_DIR = "database/seed";
const SPRITE_DIR = "data/sprites";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Minimal SQL string escaping for generated literals.
const sql = (v) =>
  v === null || v === undefined
    ? "NULL"
    : `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;

const apiFile = (...parts) => path.join(root, "data", "api", "v2", ...parts, "index.json");
const readJson = async (p) => JSON.parse(await readFile(p, "utf8"));
const sha256 = (s) => createHash("sha256").update(s).digest("hex");

function sourceCommit() {
  try {
    return execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    return "unknown (not a git checkout) — record the commit manually";
  }
}

async function loadPokemon() {
  const dir = path.join(root, "data", "api", "v2", "pokemon");
  const ids = (await readdir(dir)).map(Number).filter((id) => Number.isFinite(id) && id <= max).sort((a, b) => a - b);
  const rows = [];
  for (const id of ids) {
    const p = await readJson(apiFile("pokemon", String(id)));
    rows.push({
      id: p.id,
      name: p.name,
      baseExperience: p.base_experience ?? null, // can be null in source data
      types: [...p.types].sort((a, b) => a.slot - b.slot).map((t) => t.type.name),
      spriteUrl: p.sprites?.front_default ?? null,
    });
  }
  return rows;
}

async function loadItems() {
  const dir = path.join(root, "data", "api", "v2", "item");
  const ids = (await readdir(dir)).map(Number).filter(Number.isFinite).sort((a, b) => a - b);
  const rows = [];
  const names = new Set();
  for (const id of ids) {
    const it = await readJson(apiFile("item", String(id)));
    // api-data currently contains a duplicate Roseli Berry resource. The shop
    // model has a unique item name, so retain the lowest source id as its
    // canonical listing rather than producing a broken foreign-key seed.
    if (names.has(it.name)) continue;
    names.add(it.name);
    rows.push({
      id: it.id,
      name: it.name,
      cost: it.cost ?? 0,
      category: it.category?.name ?? null,
      spriteUrl: it.sprites?.default ?? null,
    });
  }
  return rows;
}

function pokemonSql(rows, commit) {
  const header = [
    "-- GENERATED by import-reference-data.mjs. Do not edit by hand.",
    `-- source: PokeAPI/api-data @ ${commit}`,
    `-- rows: ${rows.length} (numeric resource ids up to ${max})`,
    "-- Replaces the Gen I reference rows previously written by 001_seed_shop_data.sql.",
    "",
  ];
  const body = rows.map(
    (r) =>
      `INSERT IGNORE INTO pokemon_reference (source_id, name, base_experience, types, sprite_url) VALUES ` +
      `(${r.id}, ${sql(r.name)}, ${r.baseExperience ?? 0}, ${sql(JSON.stringify(r.types))}, ${sql(r.spriteUrl)});`
  );
  return [...header, ...body, ""].join("\n");
}

function itemsSql(rows, commit) {
  const header = [
    "-- GENERATED by import-reference-data.mjs. Do not edit by hand.",
    `-- source: PokeAPI/api-data @ ${commit}`,
    `-- rows: ${rows.length}`,
    "-- Requires item_reference from database/schema/001_create_shop_tables.sql.",
    "",
  ];
  const body = rows.map(
    (r) =>
      `INSERT IGNORE INTO item_reference (source_id, name, pokeapi_cost, category, sprite_url) VALUES ` +
      `(${r.id}, ${sql(r.name)}, ${r.cost}, ${sql(r.category)}, ${sql(r.spriteUrl)});`
  );
  return [...header, ...body, ""].join("\n");
}

const kycLevelTwoItems = new Set([
  "master-ball", "full-restore", "max-potion", "max-revive", "revival-herb",
  "max-ether", "max-elixir", "pp-max", "sacred-ash",
]);
const kycLevelOneItems = new Set([
  "ultra-ball", "great-ball", "luxury-ball", "dusk-ball", "quick-ball", "cherish-ball",
  "hyper-potion", "super-potion", "revive", "ether", "elixir", "rare-candy",
]);
function itemKycLevel(item) {
  if (kycLevelTwoItems.has(item.name)) return 2;
  if (kycLevelOneItems.has(item.name)) return 1;
  return 0;
}
function pokemonPrice(baseExperience) {
  return Math.min(1500, Math.max(200, Math.round((150 + 2 * baseExperience) / 50) * 50));
}
function pokemonStock(baseExperience, id) {
  const [low, high] = baseExperience <= 50 ? [20, 40] : baseExperience <= 100 ? [12, 24] : baseExperience <= 150 ? [6, 14] : [2, 8];
  return low + (id * 17 % (high - low + 1));
}
function itemPrice(cost) {
  return Math.min(10000, Math.max(50, Math.round((cost > 0 ? cost * 10 : 100) / 50) * 50));
}
// The seed keeps the legacy table names shop_listing/item_listing: Liquibase applies it before migration 009
// merges them into `listings`, and an applied changeset must not change (checksum).
function catalogSql(pokemon, items, commit) {
  const header = [
    "-- GENERATED by import-reference-data.mjs. Do not edit by hand.",
    `-- source: PokeAPI/api-data @ ${commit}`,
    "-- PokéMart-owned price, stock, active and KYC values are deterministic lab data.",
    "",
  ];
  const pokemonRows = pokemon.map((p) => {
    const price = pokemonPrice(p.baseExperience ?? 0);
    return `INSERT INTO shop_listing (pokemon_source_id, price, stock, active, required_kyc_level) VALUES (${p.id}, ${price}, ${pokemonStock(p.baseExperience ?? 0, p.id)}, TRUE, 0) ON DUPLICATE KEY UPDATE price=VALUES(price), stock=VALUES(stock), active=VALUES(active), required_kyc_level=VALUES(required_kyc_level);`;
  });
  const itemRows = items.map((item) => {
    const price = itemPrice(item.cost);
    const stock = 10 + (item.id * 13 % 41);
    return `INSERT INTO item_listing (item_source_id, price, stock, active, required_kyc_level) VALUES (${item.id}, ${price}, ${stock}, TRUE, ${itemKycLevel(item)}) ON DUPLICATE KEY UPDATE price=VALUES(price), stock=VALUES(stock), active=VALUES(active), required_kyc_level=VALUES(required_kyc_level);`;
  });
  return [...header, ...pokemonRows, "", ...itemRows, ""].join("\n");
}

async function downloadSprites(rows) {
  await mkdir(SPRITE_DIR, { recursive: true });
  let ok = 0;
  for (const r of rows) {
    if (!r.spriteUrl) continue;
    const res = await fetch(r.spriteUrl);
    if (!res.ok) throw new Error(`sprite ${r.id} failed: HTTP ${res.status} ${r.spriteUrl}`);
    await writeFile(path.join(SPRITE_DIR, `${r.id}.png`), Buffer.from(await res.arrayBuffer()));
    ok++;
    await sleep(50); // be polite to the sprite host
  }
  return ok;
}

async function main() {
  const commit = sourceCommit();
  await mkdir(SEED_DIR, { recursive: true });

  const pokemon = await loadPokemon();
  const pokemonOut = pokemonSql(pokemon, commit);
  await writeFile(path.join(SEED_DIR, "010_reference_pokemon.sql"), pokemonOut);

  const manifest = {
    source: "PokeAPI/api-data",
    commit,
    generatedAt: new Date().toISOString(),
    pokemon: { count: pokemon.length, maxId: max, sha256: sha256(pokemonOut) },
  };

  if (wantItems) {
    const items = await loadItems();
    const itemsOut = itemsSql(items, commit);
    await writeFile(path.join(SEED_DIR, "011_reference_items.sql"), itemsOut);
    await writeFile(path.join(SEED_DIR, "012_seed_catalog.sql"), catalogSql(pokemon, items, commit));
    manifest.items = { count: items.length, sha256: sha256(itemsOut) };
  }

  if (wantSprites) {
    manifest.spritesDownloaded = await downloadSprites(pokemon);
  }

  await mkdir("data", { recursive: true });
  await writeFile("data/reference-manifest.json", JSON.stringify(manifest, null, 2));
  console.log(JSON.stringify(manifest, null, 2));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
